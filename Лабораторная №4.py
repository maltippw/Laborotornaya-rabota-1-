class Монитор:
    """
    Базовый класс для мониторов.

    Атрибуты:
        бренд (str): Бренд монитора.
        диагональ (float): Размер диагонали экрана в дюймах.
        _серийный_номер (str): Инкапсулированный серийный номер монитора.
    """

    def init(self, бренд: str, диагональ: float, серийный_номер: str) -> None:
        """
        Конструктор базового класса.

        Аргументы:
            бренд (str): Бренд монитора.
            диагональ (float): Размер диагонали экрана в дюймах.
            серийный_номер (str): Серийный номер монитора.
        """
        self.бренд = бренд
        self.диагональ = диагональ
        self._серийный_номер = серийный_номер  # Инкапсулированный атрибут

    def str(self) -> str:
        """
        Возвращает строковое представление монитора.

        Возвращает:
            str: Строка с описанием монитора.
        """
        return f"{self.бренд} ({self.диагональ} дюймов)"

    def repr(self) -> str:
        """
        Возвращает формальное строковое представление монитора.

        Возвращает:
            str: Формальное описание монитора.
        """
        return f"Монитор(бренд={self.бренд}, диагональ={self.диагональ})"

    def получить_серийный_номер(self) -> str:
        """
        Возвращает серийный номер монитора.

        Возвращает:
            str: Серийный номер монитора.
        """
        return self._серийный_номер

    def включить(self) -> str:
        """
        Включает монитор.

        Возвращает:
            str: Сообщение о включении монитора.
        """
        return f"Монитор {self.бренд} включен."


class ИгровойМонитор(Монитор):
    """
    Дочерний класс для игровых мониторов.

    Атрибуты:
        бренд (str): Бренд монитора.
        диагональ (float): Размер диагонали экрана в дюймах.
        серийный_номер (str): Серийный номер монитора.
        частота_обновления (int): Частота обновления экрана в герцах.
    """

    def init(self, бренд: str, диагональ: float, серийный_номер: str, частота_обновления: int) -> None:
        """
        Конструктор игрового монитора.

        Аргументы:
            бренд (str): Бренд монитора.
            диагональ (float): Размер диагонали экрана в дюймах.
            серийный_номер (str): Серийный номер монитора.
            частота_обновления (int): Частота обновления экрана в герцах.
        """
        super().init(бренд, диагональ, серийный_номер)
        self.частота_обновления = частота_обновления

    def str(self) -> str:
        """
        Возвращает строковое представление игрового монитора.

        Возвращает:
            str: Строка с описанием игрового монитора.
        """
        return f"{self.бренд} ({self.диагональ} дюймов, {self.частота_обновления} Гц)"

    def repr(self) -> str:
        """
        Возвращает формальное строковое представление игрового монитора.

        Возвращает:
            str: Формальное описание игрового монитора.
        """
        return (f"ИгровойМонитор(бренд={self.бренд}, диагональ={self.диагональ}, "
                f"частота_обновления={self.частота_обновления})")

    def включить_режим(self, режим: str = "Обычный") -> str:
        """
        Включает игровой монитор в указанном режиме.

        Аргументы:
            режим (str): Выбранный режим работы монитора (например, "HDR", "Гейминг").

        Возвращает:
            str: Сообщение о включении монитора в указанном режиме.
        """
        доступные_режимы = ["Обычный", "HDR", "Гейминг"]
        if режим not in доступные_режимы:
            return f"Ошибка: режим '{режим}' недоступен."
        return f"Игровой монитор {self.бренд} включен в режиме {режим}."